-- ========================================
-- SugarGuard AI 数据库初始化脚本
-- ========================================
-- 功能：创建所有必要的表和初始化数据
-- 版本：1.0
-- 日期：2025-11-19
-- ========================================

-- 使用数据库
USE Android_health_db;

-- 设置字符集
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ========================================
-- 1. 删除已存在的表（按依赖关系倒序）
-- ========================================
-- 注意：不删除 users, user_login_logs, user_sessions 表（由后端API管理）
DROP TABLE IF EXISTS recommendation_history;
DROP TABLE IF EXISTS conversation_history;
DROP TABLE IF EXISTS user_drink_preferences;
DROP TABLE IF EXISTS meal_records;
DROP TABLE IF EXISTS daily_health_records;
DROP TABLE IF EXISTS user_health_profile;
DROP TABLE IF EXISTS drinks;
DROP TABLE IF EXISTS health_knowledge;

-- ========================================
-- 2. 创建基础表
-- ========================================

-- 2.1 饮品信息表
CREATE TABLE drinks (
    drink_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '饮品ID',
    drink_name VARCHAR(100) NOT NULL COMMENT '饮品名称',
    brand VARCHAR(100) COMMENT '品牌',
    category VARCHAR(50) COMMENT '类别（茶饮/咖啡/奶茶/果汁/碳酸饮料等）',
    sugar_content FLOAT NOT NULL COMMENT '含糖量(g/100ml)',
    calories FLOAT NOT NULL COMMENT '热量(kcal/100ml)',
    volume FLOAT DEFAULT 500.0 COMMENT '标准容量(ml)',
    caffeine FLOAT DEFAULT 0.0 COMMENT '咖啡因含量(mg/100ml)',
    fat FLOAT DEFAULT 0.0 COMMENT '脂肪含量(g/100ml)',
    protein FLOAT DEFAULT 0.0 COMMENT '蛋白质含量(g/100ml)',
    sodium FLOAT DEFAULT 0.0 COMMENT '钠含量(mg/100ml)',
    health_score INT DEFAULT 50 COMMENT '健康评分(0-100)',
    ingredients TEXT COMMENT '配料表',
    allergens VARCHAR(200) COMMENT '过敏原信息',
    image_url VARCHAR(500) COMMENT '图片URL',
    source_url VARCHAR(500) COMMENT '信息来源URL',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_name (drink_name),
    INDEX idx_brand (brand),
    INDEX idx_category (category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='饮品信息表';

-- 2.2 健康知识库表
CREATE TABLE health_knowledge (
    knowledge_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '知识ID',
    title VARCHAR(200) NOT NULL COMMENT '知识标题',
    content TEXT NOT NULL COMMENT '知识内容',
    category VARCHAR(50) COMMENT '分类（营养/疾病/运动/饮食等）',
    tags VARCHAR(200) COMMENT '标签（逗号分隔）',
    source VARCHAR(200) COMMENT '来源',
    reliability_score INT DEFAULT 70 COMMENT '可信度评分(0-100)',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_category (category),
    FULLTEXT INDEX idx_content (title, content)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='健康知识库表';

-- ========================================
-- 3. 创建用户相关表
-- ========================================

-- 3.1 用户健康档案表
-- 关联到已存在的 users 表
CREATE TABLE user_health_profile (
    profile_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '档案ID',
    user_id BIGINT UNIQUE NOT NULL COMMENT '用户ID（关联users表的id）',
    age INT NOT NULL COMMENT '年龄',
    gender ENUM('male', 'female', 'other') NOT NULL COMMENT '性别',
    height FLOAT NOT NULL COMMENT '身高(cm)',
    weight FLOAT NOT NULL COMMENT '体重(kg)',
    health_conditions TEXT COMMENT '健康状况/疾病史（JSON格式）',
    allergies VARCHAR(500) COMMENT '过敏史',
    medications VARCHAR(500) COMMENT '当前用药',
    activity_level ENUM('sedentary', 'light', 'moderate', 'active', 'very_active') DEFAULT 'moderate' COMMENT '活动水平',
    sugar_limit FLOAT DEFAULT 50.0 COMMENT '每日糖分限制(g)',
    calorie_limit FLOAT DEFAULT 2000.0 COMMENT '每日热量限制(kcal)',
    water_goal FLOAT DEFAULT 2000.0 COMMENT '每日饮水目标(ml)',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    INDEX idx_user (user_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户健康档案表';

-- 3.2 每日健康记录表
CREATE TABLE daily_health_records (
    record_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '记录ID',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    record_date DATE NOT NULL COMMENT '记录日期',
    total_sugar_intake FLOAT DEFAULT 0.0 COMMENT '当日总糖分摄入(g)',
    total_calories FLOAT DEFAULT 0.0 COMMENT '当日总热量摄入(kcal)',
    water_intake FLOAT DEFAULT 0.0 COMMENT '当日饮水量(ml)',
    exercise_minutes FLOAT DEFAULT 0.0 COMMENT '当日运动时长(分钟)',
    sleep_hours FLOAT COMMENT '睡眠时长(小时)',
    systolic_bp FLOAT COMMENT '收缩压(mmHg)',
    diastolic_bp FLOAT COMMENT '舒张压(mmHg)',
    blood_glucose FLOAT COMMENT '血糖(mmol/L)',
    weight FLOAT COMMENT '体重(kg)',
    mood ENUM('excellent', 'good', 'normal', 'bad', 'terrible') COMMENT '心情',
    notes TEXT COMMENT '备注',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UNIQUE KEY uk_user_date (user_id, record_date),
    INDEX idx_user (user_id),
    INDEX idx_date (record_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='每日健康记录表';

-- 3.3 餐食记录表
CREATE TABLE meal_records (
    meal_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '餐食ID',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    meal_date DATE NOT NULL COMMENT '日期',
    meal_time DATETIME NOT NULL COMMENT '用餐时间',
    meal_type ENUM('breakfast', 'lunch', 'dinner', 'snack') NOT NULL COMMENT '餐次类型',
    drink_id INT COMMENT '饮品ID（如果是饮品）',
    food_name VARCHAR(200) COMMENT '食物名称',
    portion_size FLOAT COMMENT '份量',
    calories FLOAT COMMENT '热量(kcal)',
    sugar_content FLOAT COMMENT '糖分(g)',
    image_path VARCHAR(500) COMMENT '照片路径',
    notes TEXT COMMENT '备注',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    INDEX idx_user (user_id),
    INDEX idx_date (meal_date),
    INDEX idx_drink (drink_id),
    FOREIGN KEY (drink_id) REFERENCES drinks(drink_id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='餐食记录表';

-- ========================================
-- 4. 创建AI功能相关表
-- ========================================

-- 4.1 用户饮品偏好表
CREATE TABLE user_drink_preferences (
    preference_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '偏好ID',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    drink_id INT NOT NULL COMMENT '饮品ID',
    preference_score INT DEFAULT 3 COMMENT '偏好评分(1-5)',
    last_consumed DATETIME COMMENT '最后饮用时间',
    times_consumed INT DEFAULT 0 COMMENT '饮用次数',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    UNIQUE KEY uk_user_drink (user_id, drink_id),
    INDEX idx_user (user_id),
    INDEX idx_drink (drink_id),
    FOREIGN KEY (drink_id) REFERENCES drinks(drink_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户饮品偏好表';

-- 4.2 对话历史表
CREATE TABLE conversation_history (
    conversation_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '对话ID',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    message TEXT NOT NULL COMMENT '用户消息',
    response TEXT NOT NULL COMMENT 'AI回复',
    intent VARCHAR(50) COMMENT '意图识别',
    context_data JSON COMMENT '上下文数据',
    feedback INT COMMENT '用户反馈(1-5)',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    INDEX idx_user (user_id),
    INDEX idx_intent (intent),
    INDEX idx_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='对话历史表';

-- 4.3 推荐历史表
CREATE TABLE recommendation_history (
    recommendation_id INT PRIMARY KEY AUTO_INCREMENT COMMENT '推荐ID',
    user_id BIGINT NOT NULL COMMENT '用户ID',
    drink_id INT NOT NULL COMMENT '饮品ID',
    recommendation_reason TEXT COMMENT '推荐理由',
    strategy VARCHAR(50) COMMENT '推荐策略',
    score FLOAT COMMENT '推荐分数',
    user_action ENUM('viewed', 'clicked', 'consumed', 'ignored') COMMENT '用户行为',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    INDEX idx_user (user_id),
    INDEX idx_drink (drink_id),
    INDEX idx_created (created_at),
    FOREIGN KEY (drink_id) REFERENCES drinks(drink_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='推荐历史表';

SET FOREIGN_KEY_CHECKS = 1;

