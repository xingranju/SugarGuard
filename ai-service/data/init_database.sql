DELIMITER $$

-- 触发器1：餐食记录插入后，更新每日健康记录
CREATE TRIGGER trg_meal_after_insert
AFTER INSERT ON meal_records
FOR EACH ROW
BEGIN
    -- 声明变量
    DECLARE v_total_sugar FLOAT DEFAULT 0;
    DECLARE v_total_calories FLOAT DEFAULT 0;
    DECLARE v_record_exists INT DEFAULT 0;
    
    -- 计算当天的总糖分和总热量
    SELECT 
        COALESCE(SUM(sugar_content), 0),
        COALESCE(SUM(calories), 0)
    INTO 
        v_total_sugar,
        v_total_calories
    FROM meal_records
    WHERE user_id = NEW.user_id 
      AND meal_date = NEW.meal_date;
    
    -- 检查当日健康记录是否存在
    SELECT COUNT(*) INTO v_record_exists
    FROM daily_health_records
    WHERE user_id = NEW.user_id 
      AND record_date = NEW.meal_date;
    
    IF v_record_exists > 0 THEN
        -- 更新已存在的记录
        UPDATE daily_health_records
        SET total_sugar_intake = v_total_sugar,
            total_calories = v_total_calories
        WHERE user_id = NEW.user_id 
          AND record_date = NEW.meal_date;
    ELSE
        -- 创建新的健康记录
        INSERT INTO daily_health_records 
            (user_id, record_date, total_sugar_intake, total_calories)
        VALUES 
            (NEW.user_id, NEW.meal_date, v_total_sugar, v_total_calories);
    END IF;
END$$

-- 触发器2：餐食记录更新后，重新计算每日健康记录
CREATE TRIGGER trg_meal_after_update
AFTER UPDATE ON meal_records
FOR EACH ROW
BEGIN
    -- 声明变量
    DECLARE v_total_sugar_new FLOAT DEFAULT 0;
    DECLARE v_total_calories_new FLOAT DEFAULT 0;
    DECLARE v_total_sugar_old FLOAT DEFAULT 0;
    DECLARE v_total_calories_old FLOAT DEFAULT 0;
    DECLARE v_record_exists_new INT DEFAULT 0;
    DECLARE v_record_exists_old INT DEFAULT 0;
    
    -- 如果日期改变了，需要更新两个日期的记录
    IF NEW.meal_date != OLD.meal_date OR NEW.user_id != OLD.user_id THEN
        -- 更新旧日期的记录
        SELECT 
            COALESCE(SUM(sugar_content), 0),
            COALESCE(SUM(calories), 0)
        INTO 
            v_total_sugar_old,
            v_total_calories_old
        FROM meal_records
        WHERE user_id = OLD.user_id 
          AND meal_date = OLD.meal_date;
        
        SELECT COUNT(*) INTO v_record_exists_old
        FROM daily_health_records
        WHERE user_id = OLD.user_id 
          AND record_date = OLD.meal_date;
        
        IF v_record_exists_old > 0 THEN
            UPDATE daily_health_records
            SET total_sugar_intake = v_total_sugar_old,
                total_calories = v_total_calories_old
            WHERE user_id = OLD.user_id 
              AND record_date = OLD.meal_date;
        END IF;
    END IF;
    
    -- 更新新日期的记录
    SELECT 
        COALESCE(SUM(sugar_content), 0),
        COALESCE(SUM(calories), 0)
    INTO 
        v_total_sugar_new,
        v_total_calories_new
    FROM meal_records
    WHERE user_id = NEW.user_id 
      AND meal_date = NEW.meal_date;
    
    SELECT COUNT(*) INTO v_record_exists_new
    FROM daily_health_records
    WHERE user_id = NEW.user_id 
      AND record_date = NEW.meal_date;
    
    IF v_record_exists_new > 0 THEN
        UPDATE daily_health_records
        SET total_sugar_intake = v_total_sugar_new,
            total_calories = v_total_calories_new
        WHERE user_id = NEW.user_id 
          AND record_date = NEW.meal_date;
    ELSE
        INSERT INTO daily_health_records 
            (user_id, record_date, total_sugar_intake, total_calories)
        VALUES 
            (NEW.user_id, NEW.meal_date, v_total_sugar_new, v_total_calories_new);
    END IF;
END$$

